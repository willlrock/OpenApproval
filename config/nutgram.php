<?php

$config = [
    'timeout' => max(1, (int) env('TELEGRAM_CLIENT_TIMEOUT', 10)),
];

if (env('TELEGRAM_PROXY')) {
    $config['client'] = [
        'proxy' => env('TELEGRAM_PROXY'),
    ];
}

return [
    // The Telegram BOT api token
    'token' => env('TELEGRAM_TOKEN'),

    // The fixed endpoint is protected by VerifyTelegramWebhook. Nutgram's
    // built-in safe mode expects md5(APP_KEY), which is a different contract.
    'safe_mode' => false,
    'webhook_secret' => env('TELEGRAM_WEBHOOK_SECRET'),
    'webhook_url' => env('TELEGRAM_WEBHOOK_URL'),

    // Extra or specific configurations
    'config' => $config,

    // Set if the service provider should automatically load
    // handlers from /routes/telegram.php
    'routes' => true,

    // Enable or disable Nutgram mixins
    'mixins' => false,

    // Path to save files generated by nutgram:make command
    'namespace' => app_path('Telegram'),

    // Set log channel
    'log_channel' => env('TELEGRAM_LOG_CHANNEL', 'null'),
];
